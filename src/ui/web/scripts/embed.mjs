// Writes ../assets.zig: every file in dist/ embedded into the likzik-ui
// binary. Run by `npm run build`; commit the result so `zig build` works
// without Node.
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, extname } from "node:path";
import { fileURLToPath } from "node:url";

const here = fileURLToPath(new URL(".", import.meta.url));
const dist = join(here, "..", "dist");
const out = join(here, "..", "..", "assets.zig");
const MIME = {
  ".html": "text/html; charset=utf-8", ".js": "text/javascript; charset=utf-8", ".css": "text/css; charset=utf-8",
  ".woff2": "font/woff2", ".woff": "font/woff", ".svg": "image/svg+xml", ".png": "image/png", ".ico": "image/x-icon",
  ".json": "application/json", ".txt": "text/plain; charset=utf-8",
};
const files = [];
(function walk(d) {
  for (const n of readdirSync(d).sort()) {
    const p = join(d, n);
    if (statSync(p).isDirectory()) walk(p); else files.push(p);
  }
})(dist);
const lines = files.map((p) => {
  const rel = relative(dist, p).split("\\").join("/");
  const mime = MIME[extname(p)];
  if (!mime) throw new Error(`no MIME type for ${rel}`);
  // Vite puts content-hashed files under assets/: safe to cache forever.
  const immutable = rel.startsWith("assets/");
  return `    .{ .path = "/${rel}", .mime = "${mime}", .immutable = ${immutable}, .data = @embedFile("web/dist/${rel}") },`;
});
writeFileSync(out, `//! GENERATED by src/ui/web/scripts/embed.mjs from src/ui/web/dist. Do not edit:
//! run \`npm run build\` in src/ui/web instead.

pub const Asset = struct { path: []const u8, mime: []const u8, immutable: bool, data: []const u8 };

pub const assets = [_]Asset{
${lines.join("\n")}
};
`);
console.log(`embed: ${files.length} files -> ${relative(process.cwd(), out)}`);
